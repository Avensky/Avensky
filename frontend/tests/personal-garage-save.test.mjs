import assert from "node:assert/strict";
import test from "node:test";
import { createServer } from "vite";

test("personal workshop edits follow the account through retry, conflict and sign-out", async t => {
  const vite = await createServer({ appType: "custom", logLevel: "error",
    server: { middlewareMode: true, hmr: false, ws: false } });
  t.after(() => vite.close());
  const load = path => vite.ssrLoadModule("/src/" + path + ".ts");
  const { setSocialConnection, receiveSocialResult } = await load("net/socialClient");
  const { useSocialStore: social } = await load("store/social/socialStore");
  const { usePersonalGarage: garage } = await load("store/social/personalGarage");
  const { DEFAULT_GARAGE_LAYOUT: defaults, validateGarageRoomLayout } = await load("game/preview/garageServiceLayout");
  const calls = [];
  setSocialConnection({ readyState: WebSocket.OPEN, send: raw => calls.push(JSON.parse(raw)) });
  t.after(() => setSocialConnection(null));
  const as = id => social.setState({ view: id ? { profile: { id } } : null });
  const ack = (call, data) => receiveSocialResult({ ok: true, request_id: call.request_id, data });
  const last = () => calls.at(-1);
  const state = garage.getState;
  as("garage-A");
  const loadA = state().reload();
  assert.equal(last().action, "garage_layout_get");
  ack(last(), { owner: "garage-A", revision: 0, layout: null });
  await loadA;
  const draft = { ...defaults, jack: { ...defaults.jack, z: defaults.jack.z + .13 } };
  assert.ok(validateGarageRoomLayout(draft));
  state().setLayout(draft);
  assert.equal(calls.length, 1);
  const save = state().save();
  assert.deepEqual(last().layout, draft);
  assert.equal(last().revision, 0);
  assert.equal(last().owner, undefined);
  receiveSocialResult({ ok: false, request_id: last().request_id, message: "Connection lost" });
  await assert.rejects(save, /Connection lost/);
  assert.equal(state().layout, draft);
  const retry = state().save();
  ack(last(), { owner: "garage-A", revision: 1, layout: defaults, conflict: true });
  await assert.rejects(retry, /another device/);
  assert.equal(state().layout, draft);
  assert.deepEqual(state().savedLayout, defaults);
  const keep = state().save();
  assert.equal(last().revision, 1);
  ack(last(), { owner: "garage-A", revision: 2, layout: draft });
  await keep;
  assert.deepEqual(state().savedLayout, draft);
  const stale = state().reload(), delayed = last();
  as(null);
  as("garage-B");
  assert.equal(state().savedLayout, null);
  assert.deepEqual(state().layout, defaults);
  ack(delayed, { owner: "garage-A", revision: 2, layout: draft });
  await stale;
  assert.equal(state().owner, "garage-B");
  assert.equal(state().status, "idle");
  const changed = state().reload();
  ack(last(), { owner: "garage-B", revision: 9, layout: { ...defaults, jack: { ...defaults.jack, x: 67 } } });
  await changed;
  assert.match(state().error, /no longer fits/);
  assert.deepEqual(state().layout, defaults);
  const reset = state().save();
  assert.equal(last().revision, 9);
  ack(last(), { owner: "garage-B", revision: 10, layout: defaults });
  await reset;
  assert.equal(state().error, "");
});
