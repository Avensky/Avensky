"""Inspect Vesper's actual head meshes and bones before drawing a new cap.

No Blender file is saved or overwritten. Run either from an opened .blend or:
blender -b --python scripts/hair/fit/inspect_character.py -- \\
    --character-glb /private/villager-female.garage.glb \\
    --report /private/fit/vesper-head.json
"""
from __future__ import annotations
import argparse
from collections import Counter
import hashlib
import json
from pathlib import Path
import sys

import bpy


def parse_args():
    args = sys.argv[sys.argv.index('--')+1:] if '--' in sys.argv else []
    p = argparse.ArgumentParser()
    p.add_argument('--character-glb', type=Path)
    p.add_argument('--report', type=Path, required=True)
    return p.parse_args(args)


def sha256(path):
    h = hashlib.sha256()
    with path.open('rb') as f:
        for chunk in iter(lambda:f.read(1024*1024), b''):
            h.update(chunk)
    return h.hexdigest()


def world_bounds(obj):
    verts = obj.data.vertices
    if not len(verts):
        return None
    low = [float('inf')] * 3
    high = [float('-inf')] * 3
    for vert in verts:
        world = obj.matrix_world @ vert.co
        for i in range(3):
            low[i] = min(low[i], float(world[i]))
            high[i] = max(high[i], float(world[i]))
    return {'min':low,'max':high}


def describe_mesh(obj):
    mesh = obj.data
    mesh.calc_loop_triangles()
    edges = Counter()
    for poly in mesh.polygons:
        for a,b in poly.edge_keys:
            edges[(a,b) if a<b else (b,a)] += 1
    materials = [mat.name if mat else None for mat in mesh.materials]
    return {
        'name':obj.name, 'vertices':len(mesh.vertices),
        'triangles':len(mesh.loop_triangles), 'polygons':len(mesh.polygons),
        'open_boundary_edges':sum(1 for value in edges.values() if value==1),
        'nonmanifold_edge_faces_gt2':sum(1 for value in edges.values() if value>2),
        'world_bounds_blender_units':world_bounds(obj),
        'materials':materials,
        'uv_sets':[u.name for u in mesh.uv_layers],
        'vertex_groups':[g.name for g in obj.vertex_groups],
        'parent':obj.parent.name if obj.parent else None,
        'armature':obj.find_armature().name if obj.find_armature() else None,
        'shape_keys':[k.name for k in mesh.shape_keys.key_blocks] if mesh.shape_keys else [],
        'scalp_or_head_name_candidate':any(word in (obj.name+' '+' '.join(filter(None,materials))).lower()
                                            for word in ('scalp','haircap','hairline','head','face','skinface')),
    }


def main():
    args = parse_args()
    imported_from = None
    if args.character_glb:
        file = args.character_glb.resolve()
        if not file.is_file() or file.suffix.lower() not in ('.glb','.gltf'):
            raise ValueError('Provide an existing character GLB or glTF')
        bpy.ops.import_scene.gltf(filepath=str(file))
        imported_from = {'path':str(file),'sha256':sha256(file)}
    elif not bpy.data.filepath:
        raise ValueError('Pass --character-glb OR open a saved .blend as the Blender background file')
    bpy.context.view_layer.update()
    meshes = [describe_mesh(obj) for obj in bpy.data.objects if obj.type=='MESH']
    armatures = [
        {'name':obj.name,'bones':[bone.name for bone in obj.data.bones],
         'head_bone_candidates':[bone.name for bone in obj.data.bones if 'head' in bone.name.lower()]}
        for obj in bpy.data.objects if obj.type=='ARMATURE'
    ]
    report = {
        'status':'INSPECTION_ONLY_NOT_FITTED',
        'source_scene':bpy.data.filepath,
        'character_glb':imported_from,
        'scene_unit_system':bpy.context.scene.unit_settings.system,
        'scene_unit_scale_length':bpy.context.scene.unit_settings.scale_length,
        'armatures':armatures,'meshes':meshes,
        'candidate_head_mesh_names':[m['name'] for m in meshes if m['scalp_or_head_name_candidate']],
        'warnings':[
            'Mesh name, material and world bounds do not prove that an actual top-of-skull surface exists.',
            'Identify real head bone, hairline boundary and head units manually before fitting.',
            'No scalp cap is generated by this inspection.'
        ],
        'source_modified':False,
    }
    args.report.parent.mkdir(parents=True,exist_ok=True)
    args.report.write_text(json.dumps(report,indent=2),encoding='utf-8')
    print('[Avensky Hair] Wrote inspection:',args.report,flush=True)
    print('[Avensky Hair] Armatures:',[(a['name'],a['head_bone_candidates']) for a in armatures],flush=True)
    print('[Avensky Hair] Possible head meshes:',report['candidate_head_mesh_names'],flush=True)


if __name__=='__main__':
    main()
